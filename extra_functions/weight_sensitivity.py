"""ACO weight sensitivity analysis on industrial_fastner (docs/optimization-spec.md section 3.2/6.6).

Not a test: a one-off analysis utility whose output feeds the thesis write-up, run once to produce
`docs/aco-weight-sensitivity-findings.md`. For each of the 7 cost-term weights (`optimization.TERMS`),
perturbs it to +50% / -50% of its default raw value (`OptimizationConfig(weights={term: ...})`, the
existing override/renormalize mechanism -- the other 6 terms keep their default raw values and
`resolve_weights` renormalizes the whole vector, preserving their ratios to each other), runs the ACO for
30 fixed seeds, and compares against the exact brute-force optimum for that same config (feasible here:
~0.5 s per call, independent of which weights are perturbed, since edge-path liveness depends only on the
AoG, not on cost weights).

Scope: the 7 `weights` dict terms only. `dir_change_axis_ratio` and the M6 alpha/beta/gamma mix
(`docs/optimization-spec.md` section 3.3, "Other parameters") are explicitly NOT covered here, even though
section 10's open item 1 inconsistently folds their tuning under "the sensitivity analysis" -- they are not
part of the `weights` override dict at all, and section 3.2's own wording ("each weight +-50%") is unambiguous.
That tuning stays open.

Uses `industrial_fastner`'s cached AoG and interference matrix (zero FreeCAD calls) via the same
`fastener()`/`brute_force()` helpers `automatic_tests/test_optimization.py` already validates O1-O15
against (imported directly, the same cross-test-file reuse `test_optimization.py` itself uses for
`test_aog.py`'s `make_inputs`) -- this keeps the sensitivity numbers directly comparable to the already-
validated brute-force baseline, and is strictly read-only against `output/industrial_fastner/`.

Usage (from repo root, environmentAAP active):

    python extra_functions/weight_sensitivity.py [--seeds 30] [--out docs/aco-weight-sensitivity-findings.md]
"""

from __future__ import annotations

import argparse
import statistics
import sys
import time
from dataclasses import replace
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT / "src"))
sys.path.insert(0, str(REPO_ROOT / "automatic_tests"))

import freecad  # noqa: E402,F401  (bootstrap for the conda build)

import optimization as op  # noqa: E402
from optimization import DEFAULT_WEIGHTS, OptimizationConfig, TERMS  # noqa: E402
from test_optimization import brute_force, fastener  # noqa: E402


def run_setting(aog, tables, cfg: OptimizationConfig, seeds: int) -> dict:
    t0 = time.perf_counter()
    optimum, n_paths = brute_force(aog, tables, cfg)
    costs = [op.optimize(aog, tables, replace(cfg, seed=s)).total_cost for s in range(seeds)]
    mean = statistics.fmean(costs)
    stdev = statistics.pstdev(costs)
    gaps = [c - optimum for c in costs]
    return {
        "optimum": optimum, "n_paths": n_paths, "mean": mean, "stdev": stdev,
        "mean_gap": statistics.fmean(gaps), "max_gap": max(gaps), "seconds": time.perf_counter() - t0,
    }


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--seeds", type=int, default=30, help="runs per setting (spec: 30)")
    ap.add_argument("--out", type=Path, default=REPO_ROOT / "docs" / "aco-weight-sensitivity-findings.md")
    args = ap.parse_args()

    aog, tables = fastener()
    print(f"industrial_fastner: N={aog.n_components}, V={aog.n_nodes}, E={aog.n_edges}")

    rows: list[tuple[str, str, dict]] = []
    baseline = run_setting(aog, tables, OptimizationConfig(), args.seeds)
    rows.append(("(baseline)", "default", baseline))
    print(f"baseline: optimum={baseline['optimum']:.6f}, mean={baseline['mean']:.6f} "
          f"(+{baseline['mean_gap']:.6f}), stdev={baseline['stdev']:.6f}, {baseline['seconds']:.1f} s")

    for term in TERMS:
        for label, factor in (("+50%", 1.5), ("-50%", 0.5)):
            cfg = OptimizationConfig(weights={term: DEFAULT_WEIGHTS[term] * factor})
            result = run_setting(aog, tables, cfg, args.seeds)
            rows.append((term, label, result))
            print(f"{term} {label}: optimum={result['optimum']:.6f}, mean={result['mean']:.6f} "
                  f"(+{result['mean_gap']:.6f}), stdev={result['stdev']:.6f}, {result['seconds']:.1f} s")

    lines = [
        "# ACO weight sensitivity on `industrial_fastner`",
        "",
        f"Generated by `extra_functions/weight_sensitivity.py --seeds {args.seeds}`, scoped to the 7 "
        "`weights` dict terms only (`docs/optimization-spec.md` section 3.2) -- `dir_change_axis_ratio` and "
        "the M6 alpha/beta/gamma mix are out of scope (see the script's own docstring); that tuning stays "
        "an open item.",
        "",
        f"Method (section 6.6): fixed seeds (`range({args.seeds})`), {args.seeds} runs per setting, mean and "
        "standard deviation of the ACO's best cost, compared against the exact brute-force optimum for that "
        "same weight config (section 8). Each non-baseline row perturbs exactly one term to +-50% of its default raw weight "
        f"(`DEFAULT_WEIGHTS[term] * factor`) via `OptimizationConfig(weights={{term: ...}})`; the other 6 "
        "terms keep their default raw values and are renormalized together with it by `resolve_weights`, "
        "preserving their ratios to each other.",
        "",
        "| Term | Perturbation | Optimum | Mean cost | Mean gap | Max gap | Std dev | Paths | Seconds |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for term, label, r in rows:
        lines.append(
            f"| {term} | {label} | {r['optimum']:.6f} | {r['mean']:.6f} | {r['mean_gap']:.6f} | "
            f"{r['max_gap']:.6f} | {r['stdev']:.6f} | {r['n_paths']} | {r['seconds']:.1f} |"
        )
    lines.append("")
    lines.append("## Observations")
    lines.append("")
    worst = max(rows[1:], key=lambda row: row[2]["mean_gap"])
    lines.append(
        f"- Largest mean convergence gap: **{worst[0]} {worst[1]}** (mean gap {worst[2]['mean_gap']:.6f} "
        f"over {args.seeds} seeds) -- a legitimate sensitivity finding (how hard the ACO's job gets under "
        "that weighting), not a bug: the brute-force optimum itself is always found exactly when it matters "
        "(see `automatic_tests/test_optimization.py` O4)."
    )
    lines.append(
        f"- Baseline (default weights): mean gap {baseline['mean_gap']:.6f}, std dev {baseline['stdev']:.6f} "
        f"over {args.seeds} seeds, for comparison."
    )

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"\nWritten to {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
